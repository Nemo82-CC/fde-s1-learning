print(f"原始列表（有重复）：{raw_tags}")
print(f"去重后：{set(raw_tags)}")
print(f"去重后个数：{len(set(raw_tags))}")

team_a = {"刘珂含", "陈驰", "张三"}
team_b = {"陈驰", "李四"}
print(f"两边都有的：{team_a & team_b}")   # 交集
print(f"合起来的所有人：{team_a | team_b}")  # 并集
print(f"只在 A 里的：{team_a - team_b}")   # 差集

