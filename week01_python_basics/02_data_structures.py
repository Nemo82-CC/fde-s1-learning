# ============================================================
# 1. 列表 list：一串有序的东西，可以增删改
# ============================================================
projects = ["A003 小奔体育", "A005 租房合同归档", "A011 北湖报账"]

print("=" * 50)
print("【1】列表 list")
print(f"全部：{projects}")
print(f"个数：{len(projects)}")
print(f"第 1 个：{projects[0]}    最后一个：{projects[-1]}")
print(f"前 2 个：{projects[:2]}")            # 切片，同样「含头不含尾」

projects.append("A012 数智安防试点")         # 末尾追加
print(f"追加一个后：{projects}")

projects.insert(0, "A001 立项")              # 插到最前面
print(f"插到第 1 位后：{projects}")

projects.remove("A001 立项")                 # 按值删除
print(f"删掉 A001 后：{projects}")

print(f"A011 在列表里吗：{'A011 北湖报账' in projects}")   # in 判断，很常用
projects.sort()
print(f"排序后：{projects}")
# 注意：sort() 直接改原列表，不返回新列表。

# ============================================================
# 2. 元组 tuple：一旦定下就不能改
# ============================================================
# 什么时候用元组？「这几项是一个整体，不该被单独改」的时候。
# 例：一条台账记录的固定字段名。

fields = ("编号", "事项", "状态", "下一步")

print("=" * 50)
print("【2】元组 tuple")
print(f"字段：{fields}")
print(f"第 2 个字段：{fields[1]}")
print(f"个数：{len(fields)}")
# 试着改成 fields[0] = "ID" 会直接报错 TypeError，这正是元组的作用：防误改。
print("（元组不能修改：fields[0] = 'ID' 会抛 TypeError，这是特性不是 bug）")

# ============================================================
# 3. 字典 dict：按「名字」取值，而不是按「位置」
# ============================================================
project = {
    "编号": "A005",
    "事项": "租房合同归档与用印",
    "状态": "进行中",
    "金额": 0,
}

print("=" * 50)
print("【3】字典 dict")
print(f"整条记录：{project}")
print(f"取「状态」：{project['状态']}")          # 中括号里写「键」
print(f"所有键：{list(project.keys())}")
print(f"所有值：{list(project.values())}")

project["状态"] = "已闭环"                       # 改值：直接赋值
project["完成日期"] = "2026-09-14"               # 新增字段
print(f"改完：{project}")

# get() 的好处：键不存在时返回默认值，而不是让程序崩掉。
print(f"取不存在的键（用 get）：{project.get('负责人', '（未填写）')}")
# 如果写成 project['负责人'] 会直接 KeyError 报错。

# ============================================================
# 4. 列表 + 字典 = 真实数据的标准形态（重点）
# ============================================================
ledger = [
    {"编号": "A003", "事项": "小奔体育商机", "状态": "进行中", "优先级": "P1"},
    {"编号": "A005", "事项": "租房合同归档", "状态": "已闭环", "优先级": "P2"},
    {"编号": "A011", "事项": "北湖第 2 批报账", "状态": "进行中", "优先级": "P0"},
]

print("=" * 50)
print("【4】列表套字典（真实数据的标准形态）")
print(f"一共 {len(ledger)} 条记录")
for row in ledger:                               # 逐条遍历
    print(f"  {row['编号']} | {row['事项']} | {row['状态']}")

# 筛选：只留「进行中」的
doing = [row for row in ledger if row["状态"] == "进行中"]
print(f"进行中的有 {len(doing)} 条：{[r['编号'] for r in doing]}")
# 上面这行叫「列表推导式」，先照抄着用，D3 讲循环时会讲清楚原理。

