# 应该输出：变量名、值，以及各自的数据类型

# ============================================================
# 2. 字符串：取长度、切片、常用方法
# ============================================================
title = "关于推进教育数字化的若干意见"

print("=" * 50)
print("【2】字符串")
print(f"总字数：{len(title)}")
print(f"第 1 个字：{title[0]}    最后 1 个字：{title[-1]}")
print(f"第 4–9 个字：{title[3:9]}")          # 切片：从下标 3 取到 8（不含 9）
print(f"把「教育」换成「教育信息化」：{title.replace('教育', '教育信息化')}")
print(f"是否以「关于」开头：{title.startswith('关于')}")
print(f"去空格：{'   两边有多余空格   '.strip()!r}")
# !r 的作用：把字符串原样显示出来，方便看清有没有空格。

# 记三条就够：
#   - 下标从 0 开始，title[0] 是第一个字符。
#   - 负数下标从末尾数：title[-1] 是最后 1 个，title[-2] 是倒数第 2 个。
#   - 切片 [起点:终点] 取到「终点前一个」：起点是包含的，终点不包含。
#     要取「最后 N 个」就写 [-N:]，冒号后面留空。
#
# 关于「方法」（后面天天用）的两条规矩：
#   - 方法要挂在某个字符串身上：title.replace('旧', '新')；只写 replace(...) 会报 NameError。
#   - 方法不会改变原来的变量，只交给你一个处理后的新结果。想看原值变没变，就 print 一下原变量。

# ============================================================
# 3. f-string：把变量塞进句子里（后面天天用）
# ============================================================
dept = "教育产品研发运营中心"

print("=" * 50)
print("【3】f-string")
print(f"{dept} 正在跟进 {project_name}，本批金额 {batch_amount:,} 元，成功率 {success_rate:.0%}")
# {batch_amount:,}  → 千分位：1,000,000
# {success_rate:.0%} → 百分比：35%

# ============================================================
# 4. 数字运算
# ============================================================
print("=" * 50)
print("【4】数字运算")
print(f"7 / 2  = {7 / 2}    # 真除法，结果一定是小数")
print(f"7 // 2 = {7 // 2}   # 整除，只保留整数部分")
print(f"7 % 2  = {7 % 2}    # 取余（余数），判断奇偶常用")
print(f"2 ** 10 = {2 ** 10}  # 幂运算")
print(f"round(3.14159, 2) = {round(3.14159, 2)}")
print(f"金额换算：{batch_amount} 元 = {batch_amount / 10000} 万元")

# ============================================================
# 5. 类型转换：做数据处理时天天遇到
# ============================================================
# 从文件 / 网页读进来的数字，读到的其实是「文本」，必须先转成数字才能算。

