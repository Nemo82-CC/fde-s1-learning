# ============================================================
# 1. 变量：给一份数据起个名字
# ============================================================
# 变量名用小写字母 + 下划线，看到名字就知道装的是什么。

from os import replace


project_name = "教育部数智安防建设试点"     # 字符串 str（文本）
batch_amount = 1000000                      # 整数 int
success_rate = 0.35                         # 浮点数 float（小数）
is_approved = False                         # 布尔值 bool（True / False）

print("=" * 50)
print("【1】变量")
print(project_name, batch_amount, success_rate, is_approved)
